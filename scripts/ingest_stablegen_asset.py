#!/usr/bin/env python3
"""
StableGen 3D Asset Ingestion & Vault Bridge
============================================
Ingests 3D assets generated by StableGen or 3D modeling tools into the
motion graphics pipeline asset vault (assets/3d_models/).

Features:
- Binary GLB parser: extracts polycount (triangles), vertex count, materials,
  bounding box dimensions, and animations with pure standard library Python.
- Automatic texture organization and metadata tagging.
- Remotion Public Sync: automatically copies/links web GLBs to public/3d_models/
  so Remotion ThreeCanvas and staticFile() can load them immediately.
- Atomic manifest.json updates.
- Formatted CLI listing and inspection tools.

Usage:
  python scripts/ingest_stablegen_asset.py --list
  python scripts/ingest_stablegen_asset.py --source model.glb --id cyber_term --genre anime --name "Cyber Terminal"
  python scripts/ingest_stablegen_asset.py --inspect cyber_term
"""

import os
import sys
import json
import shutil
import struct
import argparse
from datetime import datetime, timezone
from pathlib import Path

# Directories
WORKSPACE_ROOT = Path(__file__).resolve().parent.parent
VAULT_DIR = WORKSPACE_ROOT / "assets" / "3d_models"
PUBLIC_3D_DIR = WORKSPACE_ROOT / "public" / "3d_models"
MANIFEST_PATH = VAULT_DIR / "manifest.json"

GENRE_MAP = {
    "3d-realistic": "realistic",
    "realistic": "realistic",
    "anime": "anime",
    "motion-graphics": "props",
    "props": "props",
    "prop": "props",
    "documentary": "props",
    "podcast": "props"
}


def parse_glb_metadata(file_path: Path) -> dict:
    """
    Parses a binary GLB (glTF 2.0 binary) file to extract geometry metrics,
    material names, and dimensions without requiring external dependencies.
    """
    metadata = {
        "poly_count": 0,
        "vertex_count": 0,
        "materials": [],
        "animations": [],
        "dimensions": None,
        "is_glb": False
    }

    if not file_path.exists() or file_path.suffix.lower() != ".glb":
        return metadata

    try:
        with open(file_path, "rb") as f:
            # 12-byte header: magic (4s), version (I), length (I)
            header = f.read(12)
            if len(header) < 12:
                return metadata

            magic, version, length = struct.unpack("<4sII", header)
            if magic != b"glTF":
                return metadata

            metadata["is_glb"] = True

            # Chunk 0: JSON chunk
            chunk_header = f.read(8)
            if len(chunk_header) < 8:
                return metadata

            chunk_len, chunk_type = struct.unpack("<I4s", chunk_header)
            if chunk_type != b"JSON":
                return metadata

            json_bytes = f.read(chunk_len)
            gltf_json = json.loads(json_bytes.decode("utf-8", errors="ignore"))

            # Extract materials
            materials = gltf_json.get("materials", [])
            metadata["materials"] = [m.get("name", f"Material_{i}") for i, m in enumerate(materials)]

            # Extract animations
            animations = gltf_json.get("animations", [])
            metadata["animations"] = [a.get("name", f"Anim_{i}") for i, a in enumerate(animations)]

            accessors = gltf_json.get("accessors", [])
            meshes = gltf_json.get("meshes", [])

            total_triangles = 0
            total_vertices = 0
            bounds_min = [float("inf"), float("inf"), float("inf")]
            bounds_max = [float("-inf"), float("-inf"), float("-inf")]

            for mesh in meshes:
                for prim in mesh.get("primitives", []):
                    # Check indices for triangle count
                    indices_idx = prim.get("indices")
                    if indices_idx is not None and indices_idx < len(accessors):
                        acc = accessors[indices_idx]
                        count = acc.get("count", 0)
                        total_triangles += count // 3

                    # Check position attribute for vertex count & bounding box
                    attrs = prim.get("attributes", {})
                    pos_idx = attrs.get("POSITION")
                    if pos_idx is not None and pos_idx < len(accessors):
                        acc = accessors[pos_idx]
                        total_vertices += acc.get("count", 0)

                        if indices_idx is None:
                            total_triangles += acc.get("count", 0) // 3

                        # Bounding box
                        p_min = acc.get("min")
                        p_max = acc.get("max")
                        if p_min and len(p_min) >= 3:
                            bounds_min = [min(bounds_min[i], p_min[i]) for i in range(3)]
                        if p_max and len(p_max) >= 3:
                            bounds_max = [max(bounds_max[i], p_max[i]) for i in range(3)]

            metadata["poly_count"] = total_triangles
            metadata["vertex_count"] = total_vertices

            if bounds_min[0] != float("inf") and bounds_max[0] != float("-inf"):
                dimensions = [round(bounds_max[i] - bounds_min[i], 3) for i in range(3)]
                metadata["dimensions"] = dimensions

    except Exception as e:
        print(f"Warning: GLB inspection encountered an issue: {e}")

    return metadata


def load_manifest() -> dict:
    if not MANIFEST_PATH.exists():
        return {
            "version": "1.0.0",
            "updated_at": datetime.now(timezone.utc).isoformat(),
            "total_assets": 0,
            "assets": []
        }
    try:
        with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {"version": "1.0.0", "updated_at": "", "total_assets": 0, "assets": []}


def save_manifest(manifest: dict):
    manifest["total_assets"] = len(manifest.get("assets", []))
    manifest["updated_at"] = datetime.now(timezone.utc).isoformat()
    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)


def ingest_asset(source: str, asset_id: str, genre: str, name: str,
                 category: str = "prop", tags: str = "", textures_dir: str = None) -> dict:
    src_path = Path(source).resolve()
    if not src_path.exists():
        raise FileNotFoundError(f"Source asset file not found: {src_path}")

    asset_id = asset_id.strip().lower().replace(" ", "_").replace("-", "_")
    folder_type = GENRE_MAP.get(genre.lower(), "props")
    dest_dir = VAULT_DIR / folder_type / asset_id
    dest_dir.mkdir(parents=True, exist_ok=True)
    PUBLIC_3D_DIR.mkdir(parents=True, exist_ok=True)

    dest_model_path = dest_dir / f"model{src_path.suffix.lower()}"
    shutil.copy2(src_path, dest_model_path)

    # If it is a GLB, sync to Remotion public directory
    remotion_public_path = None
    if src_path.suffix.lower() == ".glb":
        remotion_dest = PUBLIC_3D_DIR / f"{asset_id}.glb"
        shutil.copy2(src_path, remotion_dest)
        remotion_public_path = f"public/3d_models/{asset_id}.glb"

    # Copy optional textures
    copied_textures = []
    if textures_dir:
        tex_path = Path(textures_dir).resolve()
        if tex_path.exists() and tex_path.is_dir():
            dest_tex_dir = dest_dir / "textures"
            dest_tex_dir.mkdir(exist_ok=True)
            for f in tex_path.iterdir():
                if f.is_file() and f.suffix.lower() in [".png", ".jpg", ".jpeg", ".exr", ".hdr"]:
                    shutil.copy2(f, dest_tex_dir / f.name)
                    copied_textures.append(f.name)

    # Extract metadata
    glb_meta = parse_glb_metadata(dest_model_path)

    tag_list = [t.strip() for t in tags.split(",") if t.strip()] if tags else []

    file_size_mb = round(os.path.getsize(dest_model_path) / (1024 * 1024), 2)

    asset_meta = {
        "id": asset_id,
        "name": name or asset_id.replace("_", " ").title(),
        "genre": genre,
        "category": category,
        "vault_path": str(dest_model_path.relative_to(WORKSPACE_ROOT)).replace("\\", "/"),
        "remotion_path": remotion_public_path,
        "format": src_path.suffix.lower().lstrip("."),
        "file_size_mb": file_size_mb,
        "poly_count": glb_meta.get("poly_count", 0),
        "vertex_count": glb_meta.get("vertex_count", 0),
        "dimensions_xyz": glb_meta.get("dimensions"),
        "materials": glb_meta.get("materials", []),
        "textures": copied_textures,
        "animations": glb_meta.get("animations", []),
        "tags": tag_list,
        "created_at": datetime.now(timezone.utc).isoformat()
    }

    # Save asset-level metadata
    with open(dest_dir / "asset_meta.json", "w", encoding="utf-8") as f:
        json.dump(asset_meta, f, indent=2)

    # Update global manifest
    manifest = load_manifest()
    existing_assets = manifest.get("assets", [])
    # Remove existing entry if overwriting
    existing_assets = [a for a in existing_assets if a.get("id") != asset_id]
    existing_assets.append(asset_meta)
    manifest["assets"] = existing_assets
    save_manifest(manifest)

    return asset_meta


def list_assets():
    manifest = load_manifest()
    assets = manifest.get("assets", [])

    print("\n" + "=" * 90)
    print(" 🏛️  MOTION GRAPHICS WORKFLOW - 3D ASSET VAULT MANIFEST")
    print("=" * 90)
    print(f" Total Registered Assets: {len(assets)}")
    print(f" Vault Location: {VAULT_DIR}")
    print(f" Remotion Sync Location: {PUBLIC_3D_DIR}")
    print("-" * 90)

    if not assets:
        print(" (No 3D assets currently registered. Ingest one with --source <path>)")
        print("=" * 90 + "\n")
        return

    header = f"{'ID':<20} | {'Name':<24} | {'Genre':<14} | {'Polys':<8} | {'Size':<8} | {'Remotion Sync'}"
    print(header)
    print("-" * 90)

    for a in assets:
        remotion_flag = "✅ Yes" if a.get("remotion_path") else "❌ No"
        poly_str = f"{a.get('poly_count', 0):,}" if a.get('poly_count') else "N/A"
        size_str = f"{a.get('file_size_mb', 0)} MB"
        print(f"{a['id'][:19]:<20} | {a['name'][:23]:<24} | {a['genre'][:13]:<14} | {poly_str:<8} | {size_str:<8} | {remotion_flag}")

    print("=" * 90 + "\n")


def inspect_asset(asset_id: str):
    manifest = load_manifest()
    target = None
    for a in manifest.get("assets", []):
        if a.get("id") == asset_id:
            target = a
            break

    if not target:
        print(f"\n❌ Error: Asset '{asset_id}' not found in vault manifest.")
        return

    print("\n" + "=" * 60)
    print(f" 🔍 ASSET INSPECTION: {target.get('name')} ({target.get('id')})")
    print("=" * 60)
    for k, v in target.items():
        if isinstance(v, list):
            print(f"  {k:<16}: {', '.join(str(item) for item in v) if v else 'None'}")
        else:
            print(f"  {k:<16}: {v}")
    print("=" * 60 + "\n")


def main():
    parser = argparse.ArgumentParser(description="StableGen 3D Asset Ingestion & Vault Bridge")
    parser.add_argument("--source", type=str, help="Path to source 3D asset (.glb, .blend, .fbx)")
    parser.add_argument("--id", type=str, help="Unique asset identifier (e.g. server_blade, cyber_terminal)")
    parser.add_argument("--genre", type=str, default="realistic", choices=["3d-realistic", "realistic", "anime", "motion-graphics", "props", "podcast", "documentary"], help="Target production genre")
    parser.add_argument("--name", type=str, help="Human-readable asset display name")
    parser.add_argument("--category", type=str, default="prop", help="Category: hardware, datacenter, character, environment, prop")
    parser.add_argument("--tags", type=str, default="", help="Comma-separated tags")
    parser.add_argument("--textures", type=str, default=None, help="Optional directory containing PBR texture maps")
    parser.add_argument("--list", action="store_true", help="List all registered 3D assets in the vault")
    parser.add_argument("--inspect", type=str, help="Inspect detailed metadata of a specific asset ID")

    args = parser.parse_args()

    if args.list:
        list_assets()
        return

    if args.inspect:
        inspect_asset(args.inspect)
        return

    if not args.source or not args.id:
        parser.print_help()
        sys.exit(1)

    print(f"\n🚀 Ingesting 3D asset '{args.id}' from: {args.source}")
    result = ingest_asset(
        source=args.source,
        asset_id=args.id,
        genre=args.genre,
        name=args.name,
        category=args.category,
        tags=args.tags,
        textures_dir=args.textures
    )

    print(f"✅ Asset ingested successfully!")
    print(f"   - Vault Destination: {result['vault_path']}")
    if result.get("remotion_path"):
        print(f"   - Remotion Web Sync: {result['remotion_path']}")
    print(f"   - Polygons: {result.get('poly_count', 0):,}")
    print(f"   - File Size: {result.get('file_size_mb')} MB")
    print(f"   - Materials: {', '.join(result.get('materials', [])) or 'None'}")
    print(f"\nManifest updated. Run with --list to view all assets.\n")


if __name__ == "__main__":
    main()
